function buildMansionWorld(defs){
 const MR={},portals={},props={},cells={},err=m=>{throw new Error('[rooms] '+m);};
 const center=(c,r)=>[c*ROOM_TILE+8,(r+1)*ROOM_TILE];
 for(const d of defs){
  const W=d.cw||0,rows=d.rows,cols=d.rows[0].length;
  if(cols%ROOM_CELL_COLS||rows.length%ROOM_CELL_ROWS)err(`${d.id}: size ${cols}x${rows.length} must be a multiple of 16x15`);
  d.cw=cols/ROOM_CELL_COLS;d.ch=rows.length/ROOM_CELL_ROWS;
  rows.forEach((row,i)=>{if(row.length!==cols)err(`${d.id}: row ${i} has ${row.length} chars, expected ${cols}`);for(const ch of row)if(!ROOM_SOLID_CHARS.includes(ch)&&!ROOM_MARK_CHARS.includes(ch))err(`${d.id}: unknown tile '${ch}' in row ${i}`);});
  for(let y=0;y<d.ch;y++)for(let x=0;x<d.cw;x++){const k=(d.cx+x)+','+(d.cy+y);if(cells[k])err(`${d.id} overlaps ${cells[k]} at world cell ${k}`);cells[k]=d.id;}
  const at=(c,r)=>r<0||r>=rows.length||c<0||c>=cols?'#':rows[r][c];
  // Merge solid tiles into rectangles (row runs, then stack identical runs).
  const rects=(ch,h=16)=>{const runs=[];for(let r=0;r<rows.length;r++){let c=0;while(c<cols){if(rows[r][c]!==ch){c++;continue;}let e=c;while(e<cols&&rows[r][e]===ch)e++;runs.push([c,r,e-c]);c=e;}}
   const out=[];for(const run of runs){const prev=out.find(o=>o.c===run[0]&&o.n===run[2]&&o.r+o.h===run[1]&&h===16);if(prev)prev.h++;else out.push({c:run[0],r:run[1],n:run[2],h:1});}
   return out.map(o=>[o.c*16,o.r*16,o.n*16,h===16?o.h*16:h]);};
  const bbox=ch=>{let a=null;rows.forEach((row,r)=>[...row].forEach((x,c)=>{if(x!==ch)return;a=a?[Math.min(a[0],c),Math.min(a[1],r),Math.max(a[2],c),Math.max(a[3],r)]:[c,r,c,r];}));return a&&[a[0]*16,a[1]*16,(a[2]-a[0]+1)*16,(a[3]-a[1]+1)*16];};
  const marks=[];rows.forEach((row,r)=>[...row].forEach((ch,c)=>{if(!'#=gk.|'.includes(ch))marks.push({ch,c,r,x:c*16+8,y:(r+1)*16});}));
  marks.sort((a,b)=>a.x-b.x||a.y-b.y);
  const one=ch=>{const m=marks.filter(m=>m.ch===ch);if(m.length>1)err(`${d.id}: only one '${ch}' allowed`);return m[0]?[m[0].x,m[0].y]:undefined;};
  for(const m of marks)if(!'fKOPC'.includes(m.ch)&&!ROOM_SOLID_CHARS.includes(at(m.c,m.r+1)))err(`${d.id}: marker '${m.ch}' at col ${m.c} row ${m.r} must stand on a solid tile`);
  const r={name:d.name,area:d.area,w:cols*16,h:rows.length*16,map:[d.cx,d.cy],cell:[d.cx,d.cy,d.cw,d.ch],tone:d.tone,grid:rows,
   floor:rects('#'),blocks:rects('=',8),doors:[],enemies:[],decor:marks.filter(m=>'KOPC'.includes(m.ch)).map(m=>[m.ch,m.x,m.y])};
  if(d.hub)r.hub=true;
  const opt={cp:one('S'),seal:one('s'),boss:one('B'),goal:one('G'),extension:one('X'),npc:one('N')};for(const k in opt)if(opt[k])r[k]=opt[k];
  if(r.seal)r.seal=[r.seal[0],r.seal[1]-2];
  const lever=one('L');if(lever){if(!d.lever)err(`${d.id}: 'L' needs def.lever {flag,label}`);r.lever={x:lever[0],y:lever[1],...d.lever};}
  const kg=bbox('k');if(kg){if(!d.lever)err(`${d.id}: 'k' gate needs def.lever`);r.switchGate=kg;}
  const sg=bbox('g');if(sg)r.gate=sg;
  if(d.lift)r.lift={x:d.lift.col*16,w:d.lift.w*16,stops:d.lift.stops,...(d.lift.initialStop!=null?{initialStop:d.lift.initialStop}:{})};
  const vents=marks.filter(m=>m.ch==='u');if(vents.length)r.vents=vents.map((m,i)=>({x:m.x,y:m.y,offset:(d.ventOffsets||[])[i]??i*60}));
  for(const m of marks.filter(m=>m.ch==='w'||m.ch==='f')){
   if(m.ch==='w'){let a=m.c,b=m.c;while(a>0&&at(a-1,m.r)==='.'||a>0&&!ROOM_SOLID_CHARS.includes(at(a-1,m.r))&&ROOM_SOLID_CHARS.includes(at(a-1,m.r+1))){if(m.c-a>=4)break;a--;}while(!ROOM_SOLID_CHARS.includes(at(b+1,m.r))&&ROOM_SOLID_CHARS.includes(at(b+1,m.r+1))&&b-m.c<4)b++;r.enemies.push(['walk',m.x,m.y,a*16+8,b*16+8]);}
   else r.enemies.push(['fly',m.x,m.y,m.x-48,m.x+48]);}
  const kinds={c:'candle',v:'vase',x:'box'};const pr=marks.filter(m=>kinds[m.ch]).map(m=>[kinds[m.ch],m.x,m.y,'water']);if(pr.length)props[d.id]=pr;
  const w=one('W');if(w)portals[d.id]={x:w[0],y:w[1],...(d.portalNeed?{need:d.portalNeed}:{})};
  r._marks=marks;r._def=d;MR[d.id]=r;
 }
 // Doors: digits pair through def.links, 'D' pairs across the room edge on the world grid.
 const roomAt=(x,y)=>cells[x+','+y];
 for(const[id,r]of Object.entries(MR)){const d=r._def;
  for(const m of r._marks){
   if(m.ch==='D'){const cc=Math.floor(m.c/16),cy=Math.floor(m.r/15),side=d.cw===1?(m.c<8?-1:1):cc===0?-1:cc===d.cw-1?1:0;
    if(!side)err(`${id}: edge door 'D' at col ${m.c} must be in the first or last screen column`);
    const wx=d.cx+cc+side,wy=d.cy+cy,to=roomAt(wx,wy);if(!to)err(`${id}: edge door at col ${m.c} row ${m.r} has no neighbouring room at world cell ${wx},${wy}`);
    const t=MR[to],td=t._def,partner=t._marks.filter(n=>n.ch==='D'&&td.cx+Math.floor(n.c/16)===wx&&td.cy+Math.floor(n.r/15)===wy&&(td.cw===1?(n.c<8?-1:1):Math.floor(n.c/16)===0?-1:1)===-side);
    if(partner.length!==1)err(`${id}: edge door at col ${m.c} row ${m.r} needs exactly one matching 'D' in ${to} (found ${partner.length})`);
    const p=partner[0];r.doors.push({x:m.x,y:m.y,to,at:[p.x+side*16,p.y],label:t.name});}
   else if(/[1-9]/.test(m.ch)){const link=(d.links||{})[m.ch];if(!link)err(`${id}: door '${m.ch}' has no def.links entry`);const[to,key]=link.split(':');const t=MR[to];if(!t)err(`${id}: door '${m.ch}' links to unknown room ${to}`);
    const p=t._marks.find(n=>n.ch===key);if(!p)err(`${id}: door '${m.ch}' -> ${link}: marker not found`);
    const door={x:m.x,y:m.y,to,at:[p.x,p.y],label:t.name};const need=(d.need||{})[m.ch];if(need)door.need=need;r.doors.push(door);}
  }
  if(d.extension&&r.extension){const[to,key]=d.extension.link.split(':'),p=MR[to]&&MR[to]._marks.find(n=>n.ch===key);if(!p)err(`${id}: extension link ${d.extension.link} not found`);r.extensionDoor={to,at:[p.x,p.y],...(d.extension.onEnterFlag?{onEnterFlag:d.extension.onEnterFlag}:{}),...(d.extension.need?{need:d.extension.need}:{})};}
 }
 for(const r of Object.values(MR)){delete r._marks;delete r._def;}
 // Warp list order follows def.warpOrder (lower first), then ROOM_DEFS order.
 const order=Object.keys(portals).sort((a,b)=>((defs.find(d=>d.id===a).warpOrder??99)-(defs.find(d=>d.id===b).warpOrder??99)));
 return{MR,portals:Object.fromEntries(order.map(k=>[k,portals[k]])),props,cells};
}
